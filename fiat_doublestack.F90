MODULE FIAT_DOUBLESTACK

USE ISO_C_BINDING, ONLY : C_INT8_T,C_SIZE_T,C_PTR

PRIVATE


PUBLIC :: DOUBLESTACK
PUBLIC :: FIAT_DOUBLESTACK_NEW,FIAT_DOUBLESTACK_DELETE,FIAT_DOUBLESTACK_ALLOCATE,FIAT_DOUBLESTACK_DEALLOCATE

TYPE DOUBLESTACK_TYPE
  INTEGER(KIND=C_INT8_T), POINTER :: PTR(:)
  INTEGER(KIND=C_SIZE_T) :: INDEX_UP_0
  INTEGER(KIND=C_SIZE_T) :: INDEX_LOW_0
  INTEGER(KIND=C_SIZE_T) :: INDEX_UP
  INTEGER(KIND=C_SIZE_T) :: INDEX_LOW

END TYPE

CONTAINS

SUBROUTINE FIAT_DOUBLESTACK_NEW(DOUBLESTACK,SIZE_BYTES)
  USE ISO_C_BINDING, ONLY : C_INT8_T,C_SIZE_T,C_PTR
  TYPE(DOUBLESTACK_TYPE), INTENT(OUT) :: DOUBLESTACK
  INTEGER(C_SIZE_T), INTENT(IN) :: SIZE_BYTES

  ALLOCATE(DOUBLESTACK%PTR(SIZE_BYTES))
  DOUBLESTACK%INDEX_UP=SIZE_BYTES
  DOUBLESTACK%INDEX_UP_0=SIZE_BYTES
  DOUBLESTACK%INDEX_LOW=1
  DOUBLESTACK%INDEX_LOW_0=1
END SUBROUTINE FIAT_DOUBLESTACK_NEW

SUBROUTINE FIAT_DOUBLESTACK_DELETE(DOUBLESTACK)
  USE ISO_C_BINDING, ONLY : C_INT8_T,C_SIZE_T,C_PTR
  TYPE(DOUBLESTACK_TYPE) :: DOUBLESTACK
  IF ((DOUBLESTACK%INDEX_UP<DOUBLESTACK%INDEX_UP_0) .OR. (DOUBLESTACK%INDEX_LOW>DOUBLESTACK%INDEX_LOW_0)) THEN
    WRITE (0,*) "ERROR : DELETING FIAT_DOUBLESTACK WITH DATA STILL ALLOCATED"
    CALL ABORT
  ELSE
    DEALLOCATE(DOUBLESTACK%PTR)
  ENDIF
END SUBROUTINE FIAT_DOUBLESTACK_DELETE

SUBROUTINE FIAT_DOUBLESTACK_ALLOCATE(DOUBLESTACK, SIZE_BYTES, SIDE, PTR)
  USE ISO_C_BINDING, ONLY : C_INT8_T,C_SIZE_T,C_PTR
  TYPE (DOUBLESTACK_TYPE), INTENT(INOUT) :: DOUBLESTACK
  INTEGER (C_SIZE_T), INTENT(IN) :: SIZE_BYTES
  INTEGER (C_INT8_T), INTENT(IN) :: SIDE
  INTEGER(C_INT8_T), POINTER, INTENT(OUT) :: PTR(:)

  IF (SIDE==0) THEN
    IF (DOUBLESTACK%INDEX_LOW+SIZE_BYTES>DOUBLESTACK%INDEX_UP) THEN
      WRITE (0,*) "ERROR : DOUBLESTACK OVERALLOCATED, LOWER SIDE"
      CALL ABORT
    ELSE
      PTR(1:SIZE_BYTES)=>DOUBLESTACK%PTR(DOUBLESTACK%INDEX_LOW:DOUBLESTACK%INDEX_LOW+SIZE_BYTES-1)
      DOUBLESTACK%INDEX_LOW=DOUBLESTACK%INDEX_LOW+SIZE_BYTES
    ENDIF
  ELSEIF (SIDE==1) THEN
    IF (DOUBLESTACK%INDEX_UP-SIZE_BYTES<DOUBLESTACK%INDEX_LOW) THEN
      WRITE (0,*) "ERROR : DOUBLESTACK OVERALLOCATED, UPPER SIDE"
      CALL ABORT
    ELSE
      PTR(1:SIZE_BYTES)=>DOUBLESTACK%PTR(DOUBLESTACK%INDEX_UP-SIZE_BYTES+1:DOUBLESTACK%INDEX_UP)
      DOUBLESTACK%INDEX_UP=DOUBLESTACK%INDEX_UP-SIZE_BYTES
    ENDIF
  ELSE
    WRITE (0,*) "ERROR : WRONG VALUE FOR SIDE, FIAT_DOUBLESTACK_ALLOCATE"
    CALL ABORT
  ENDIF
   
END SUBROUTINE FIAT_DOUBLESTACK_ALLOCATE

SUBROUTINE FIAT_DOUBLESTACK_DEALLOCATE(DOUBLESTACK, SIDE, PTR)
  USE ISO_C_BINDING, ONLY : C_INT8_T,C_SIZE_T,C_PTR
  TYPE (DOUBLESTACK_TYPE), INTENT(INOUT) :: DOUBLESTACK
  INTEGER (C_INT8_T), INTENT(IN) :: SIDE
  INTEGER(KIND=C_INT8_T), POINTER, INTENT(INOUT) :: PTR(:)
  INTEGER (C_SIZE_T) :: SIZE_BYTES

  SIZE_BYTES=SIZE(PTR)
  IF (SIDE==0) THEN
    IF (DOUBLESTACK%INDEX_LOW-SIZE_BYTES<DOUBLESTACK%INDEX_LOW_0) THEN
      WRITE (0,*) "ERROR : FIAT_DOUBLESTACK_DEALLOCATE, NOT ENOUGH DATA, LOWER SIDE"
      CALL ABORT
    ELSE
      PTR=>NULL()
      DOUBLESTACK%INDEX_LOW=DOUBLESTACK%INDEX_LOW-SIZE_BYTES
    ENDIF
  ELSEIF (SIDE==1) THEN
    IF (DOUBLESTACK%INDEX_UP+SIZE_BYTES>DOUBLESTACK%INDEX_UP_0) THEN
      WRITE (0,*) "ERROR : FIAT_DOUBLESTACK_DEALLOCATE, NOT ENOUGH DATA, UPPER SIDE"
      CALL ABORT
    ELSE
      PTR=>NULL() 
      DOUBLESTACK%INDEX_UP=DOUBLESTACK%INDEX_UP+SIZE_BYTES
    ENDIF
  ELSE
    WRITE (0,*) "ERROR : WRONG VALUE FOR SIDE, FIAT_DOUBLESTACK_DEALLOCATE"
    CALL ABORT
  ENDIF

END SUBROUTINE FIAT_DOUBLESTACK_DEALLOCATE

END MODULE FIAT_DOUBLESTACK
