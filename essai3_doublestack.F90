PROGRAM ESSAI_STACK

USE MPL_DOUBLESTACK_MOD, ONLY : MPL_DOUBLESTACK
USE EC_PARKIND, ONLY     : JPIM, JPIB, JPRM, JPRD
USE ISO_C_BINDING, ONLY : C_INT8_T, C_LOC,C_INTPTR_T

IMPLICIT NONE
INTEGER(KIND=C_INT8_T), PARAMETER :: MPL_LOWER=0
INTEGER(KIND=C_INT8_T), PARAMETER :: MPL_UPPER=1

INTEGER(KIND=JPIB) :: IL_MPL_DOUBLESTACK_SIZE
INTEGER(KIND=JPIB) :: IL_BUF_SIZE(1)
INTEGER(KIND=JPIB) :: CPTR

REAL(KIND=JPRM), POINTER, CONTIGUOUS :: FOUBUF(:), FOUBUF_IN(:)

IL_MPL_DOUBLESTACK_SIZE=512*1024_8**2
CALL MPL_DOUBLESTACK%INIT(IL_MPL_DOUBLESTACK_SIZE)

!with IL_BUF_SIZE=128*1024_8**2+1 , buddy_malloc cannot allocate
!with IL_BUF_SIZE=                , tbb cannot allocate
DO CPTR=128*1024_8**2,256*1024_8**2,8*1024_8**2

  !the buffer size is given in number of integer, of length 4 bytes
  IL_BUF_SIZE(1)=CPTR/4  

  WRITE(0,*) "ALLOCATING TWO ARRAY OF SIZE",CPTR,"EACH"
  CALL MPL_DOUBLESTACK%ALLOCATE(FOUBUF,IL_BUF_SIZE,SIDE_PARAM=MPL_LOWER)
  CALL MPL_DOUBLESTACK%ALLOCATE(FOUBUF_IN,IL_BUF_SIZE,SIDE_PARAM=MPL_UPPER)
  FOUBUF=1.
  FOUBUF_IN(:)=FOUBUF(:)+1.
  WRITE(0,*) "FOUBUF_IN(1)=",FOUBUF_IN(1)
  CALL MPL_DOUBLESTACK%DEALLOCATE(FOUBUF)
  CALL MPL_DOUBLESTACK%DEALLOCATE(FOUBUF_IN)
ENDDO

CALL MPL_DOUBLESTACK%FINAL

END PROGRAM ESSAI_STACK
