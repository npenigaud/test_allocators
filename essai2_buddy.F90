PROGRAM ESSAI_BUDDY

USE ISO_C_BINDING
USE MPL_HEAP_MOD, ONLY : MPL_HEAP
USE EC_PARKIND, ONLY     : JPIM, JPIB, JPRM, JPRD

IMPLICIT NONE

INTEGER*8 :: IL_MPL_HEAP_SIZE
INTEGER*4 :: IL_BUF_SIZE(1)
INTEGER(KIND=JPIB) :: CPTR

REAL(KIND=JPRM), POINTER :: FOUBUF(:), FOUBUF_IN(:)

IL_MPL_HEAP_SIZE=512*1024_8**2
CALL MPL_HEAP%INIT(IL_MPL_HEAP_SIZE)

!with IL_BUF_SIZE=128*1024_8**2+1 , buddy_malloc cannot allocate
!with IL_BUF_SIZE=                , tbb cannot allocate
DO CPTR=128*1024_8**2,256*1024_8**2,8*1024_8**2

  !the buffer size is given in number of integer, of length 4 bytes
  IL_BUF_SIZE(1)=CPTR/4+1  

  WRITE(0,*) "ALLOCATING TWO ARRAY OF SIZE",CPTR,"EACH"
  CALL MPL_HEAP%ALLOCATE(FOUBUF,IL_BUF_SIZE)
  CALL MPL_HEAP%ALLOCATE(FOUBUF_IN,IL_BUF_SIZE)
  FOUBUF=1.
  FOUBUF_IN(:)=FOUBUF(:)+1.
  WRITE(0,*) "FOUBUF_IN(1)=",FOUBUF_IN(1)
  CALL MPL_HEAP%DEALLOCATE(FOUBUF)
  CALL MPL_HEAP%DEALLOCATE(FOUBUF_IN)
ENDDO


END PROGRAM ESSAI_BUDDY
