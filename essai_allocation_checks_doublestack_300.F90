PROGRAM ESSAI_ALLOCATION_CHECKS_STACK_300

USE MPL_DOUBLESTACK_MOD, ONLY : MPL_DOUBLESTACK
USE EC_PARKIND, ONLY     : JPIM, JPIB, JPRM, JPRD
USE ISO_C_BINDING, ONLY : C_INT8_T

IMPLICIT NONE
INTEGER(KIND=C_INT8_T), PARAMETER :: MPL_LOWER=0
INTEGER(KIND=C_INT8_T), PARAMETER :: MPL_UPPER=1
INTEGER*8 :: IL_MPL_DOUBLESTACK_SIZE
INTEGER*4 :: IL_BUF_SIZE(1)

REAL(KIND=JPRD), POINTER :: FOUBUF(:,:), FOUBUF_IN(:,:)
REAL(KIND=JPRM), POINTER :: AUX(:,:,:)
INTEGER(KIND=JPIM), POINTER :: IFOUBUF(:,:), IFOUBUF_IN(:,:)

INTEGER(KIND=JPIM) :: UBOUNDS_REAL(3)
INTEGER(KIND=JPIM) :: UBOUNDS_DOUBLE(2)
INTEGER(KIND=JPIM) :: UBOUNDS_INT(2)

IL_MPL_DOUBLESTACK_SIZE=300*1024_8**2  ! 300 MBytes
!IL_BUF_SIZE=32*1024_8**2+1       ! un peu plus de 128 MBytes, en nombre d'éléments

UBOUNDS_REAL(1)=16
UBOUNDS_REAL(2)=33
UBOUNDS_REAL(3)=5

UBOUNDS_DOUBLE(1)=21*1024_8+1
UBOUNDS_DOUBLE(2)=105

UBOUNDS_INT(1)=43
UBOUNDS_INT(2)=105

CALL MPL_DOUBLESTACK%INIT(IL_MPL_DOUBLESTACK_SIZE)

WRITE (0,*) "Allocation and deallocation in proper order"
!allocation de FOUBUF sur le bas de la pile
CALL MPL_DOUBLESTACK%ALLOCATE(FOUBUF,UBOUNDS_DOUBLE,SIDE_PARAM=MPL_LOWER)
CALL MPL_DOUBLESTACK%ALLOCATE(IFOUBUF,UBOUNDS_INT,SIDE_PARAM=MPL_LOWER)

!allocation de FOUBUF_IN sur le haut de la pile
CALL MPL_DOUBLESTACK%ALLOCATE(FOUBUF_IN,UBOUNDS_DOUBLE,SIDE_PARAM=MPL_UPPER)
CALL MPL_DOUBLESTACK%ALLOCATE(IFOUBUF_IN,UBOUNDS_INT,SIDE_PARAM=MPL_UPPER)

FOUBUF=1.
FOUBUF_IN(:,:)=FOUBUF(:,:)+1.

IFOUBUF=41
IFOUBUF_IN(:,:)=FOUBUF(:,:)+1

WRITE(0,*) "FOUBUF_IN(2,3)",FOUBUF_IN(2,3)
WRITE(0,*) "SIZE(FOUBUF), SIZE(FOUBUF_IN)",SIZE(FOUBUF),SIZE(FOUBUF_IN)
WRITE(0,*) "SHAPE(FOUBUF), SHAPE(FOUBUF_IN)",SHAPE(FOUBUF),SHAPE(FOUBUF_IN)
WRITE(0,*) "KIND(FOUBUF), KIND(FOUBUF_IN)",KIND(FOUBUF),KIND(FOUBUF_IN)

WRITE(0,*) "IFOUBUF_IN(3,2)",IFOUBUF_IN(3,2)
WRITE(0,*) "SIZE(IFOUBUF), SIZE(IFOUBUF_IN)",SIZE(IFOUBUF),SIZE(IFOUBUF_IN)
WRITE(0,*) "SHAPE(IFOUBUF), SHAPE(IFOUBUF_IN)",SHAPE(IFOUBUF),SHAPE(IFOUBUF_IN)
WRITE(0,*) "KIND(IFOUBUF), KIND(IFOUBUF_IN)",KIND(IFOUBUF),KIND(IFOUBUF_IN)


CALL MPL_DOUBLESTACK%DEALLOCATE(IFOUBUF,SIDE_PARAM=MPL_LOWER)
CALL MPL_DOUBLESTACK%DEALLOCATE(FOUBUF,SIDE_PARAM=MPL_LOWER)

CALL MPL_DOUBLESTACK%DEALLOCATE(IFOUBUF_IN,SIDE_PARAM=MPL_UPPER)
CALL MPL_DOUBLESTACK%DEALLOCATE(FOUBUF_IN,SIDE_PARAM=MPL_UPPER)

WRITE (0,*) "==========================================="
WRITE (0,*) "Multiple allocation and deallocation in correct order, lower side"
CALL MPL_DOUBLESTACK%ALLOCATE(FOUBUF,UBOUNDS_DOUBLE,SIDE_PARAM=MPL_LOWER)
CALL MPL_DOUBLESTACK%ALLOCATE(IFOUBUF,UBOUNDS_INT,SIDE_PARAM=MPL_LOWER)
CALL MPL_DOUBLESTACK%ALLOCATE(FOUBUF_IN,UBOUNDS_DOUBLE,SIDE_PARAM=MPL_LOWER)
CALL MPL_DOUBLESTACK%ALLOCATE(IFOUBUF_IN,UBOUNDS_INT,SIDE_PARAM=MPL_LOWER)
CALL MPL_DOUBLESTACK%ALLOCATE(AUX,UBOUNDS_REAL,SIDE_PARAM=MPL_LOWER)

CALL MPL_DOUBLESTACK%DEALLOCATE(AUX,SIDE_PARAM=MPL_LOWER)
CALL MPL_DOUBLESTACK%DEALLOCATE(IFOUBUF_IN,SIDE_PARAM=MPL_LOWER)
CALL MPL_DOUBLESTACK%DEALLOCATE(FOUBUF_IN,SIDE_PARAM=MPL_LOWER)
CALL MPL_DOUBLESTACK%DEALLOCATE(IFOUBUF,SIDE_PARAM=MPL_LOWER)
CALL MPL_DOUBLESTACK%DEALLOCATE(FOUBUF,SIDE_PARAM=MPL_LOWER)

WRITE (0,*) "==========================================="
WRITE (0,*) "Multiple allocation and deallocation in correct order, upper side"
CALL MPL_DOUBLESTACK%ALLOCATE(FOUBUF,UBOUNDS_DOUBLE,SIDE_PARAM=MPL_UPPER)
CALL MPL_DOUBLESTACK%ALLOCATE(IFOUBUF,UBOUNDS_INT,SIDE_PARAM=MPL_UPPER)
CALL MPL_DOUBLESTACK%ALLOCATE(FOUBUF_IN,UBOUNDS_DOUBLE,SIDE_PARAM=MPL_UPPER)
CALL MPL_DOUBLESTACK%ALLOCATE(IFOUBUF_IN,UBOUNDS_INT,SIDE_PARAM=MPL_UPPER)
CALL MPL_DOUBLESTACK%ALLOCATE(AUX,UBOUNDS_REAL,SIDE_PARAM=MPL_UPPER)

CALL MPL_DOUBLESTACK%DEALLOCATE(AUX,SIDE_PARAM=MPL_UPPER)
CALL MPL_DOUBLESTACK%DEALLOCATE(IFOUBUF_IN,SIDE_PARAM=MPL_UPPER)
CALL MPL_DOUBLESTACK%DEALLOCATE(FOUBUF_IN,SIDE_PARAM=MPL_UPPER)
CALL MPL_DOUBLESTACK%DEALLOCATE(IFOUBUF,SIDE_PARAM=MPL_UPPER)
CALL MPL_DOUBLESTACK%DEALLOCATE(FOUBUF,SIDE_PARAM=MPL_UPPER)

WRITE (0,*) "==========================================="
WRITE (0,*) "Allocation and deallocation in incorrect order"

!allocation de FOUBUF sur le bas de la pile
CALL MPL_DOUBLESTACK%ALLOCATE(FOUBUF,UBOUNDS_DOUBLE,SIDE_PARAM=MPL_LOWER)
CALL MPL_DOUBLESTACK%ALLOCATE(IFOUBUF,UBOUNDS_INT,SIDE_PARAM=MPL_LOWER)

!allocation de FOUBUF_IN sur le haut de la pile
CALL MPL_DOUBLESTACK%ALLOCATE(FOUBUF_IN,UBOUNDS_DOUBLE,SIDE_PARAM=MPL_UPPER)
CALL MPL_DOUBLESTACK%ALLOCATE(IFOUBUF_IN,UBOUNDS_INT,SIDE_PARAM=MPL_UPPER)

FOUBUF=1.
FOUBUF_IN(:,:)=FOUBUF(:,:)+1.

IFOUBUF=41
IFOUBUF_IN(:,:)=FOUBUF(:,:)+1

WRITE(0,*) "FOUBUF_IN(2,3)",FOUBUF_IN(2,3)
WRITE(0,*) "SIZE(FOUBUF), SIZE(FOUBUF_IN)",SIZE(FOUBUF),SIZE(FOUBUF_IN)
WRITE(0,*) "SHAPE(FOUBUF), SHAPE(FOUBUF_IN)",SHAPE(FOUBUF),SHAPE(FOUBUF_IN)
WRITE(0,*) "KIND(FOUBUF), KIND(FOUBUF_IN)",KIND(FOUBUF),KIND(FOUBUF_IN)

WRITE(0,*) "IFOUBUF_IN(3,2)",IFOUBUF_IN(3,2)
WRITE(0,*) "SIZE(IFOUBUF), SIZE(IFOUBUF_IN)",SIZE(IFOUBUF),SIZE(IFOUBUF_IN)
WRITE(0,*) "SHAPE(IFOUBUF), SHAPE(IFOUBUF_IN)",SHAPE(IFOUBUF),SHAPE(IFOUBUF_IN)
WRITE(0,*) "KIND(IFOUBUF), KIND(IFOUBUF_IN)",KIND(IFOUBUF),KIND(IFOUBUF_IN)

CALL MPL_DOUBLESTACK%DEALLOCATE(FOUBUF,SIDE_PARAM=MPL_LOWER)
CALL MPL_DOUBLESTACK%DEALLOCATE(IFOUBUF,SIDE_PARAM=MPL_LOWER)

CALL MPL_DOUBLESTACK%DEALLOCATE(IFOUBUF_IN,SIDE_PARAM=MPL_UPPER)
CALL MPL_DOUBLESTACK%DEALLOCATE(FOUBUF_IN,SIDE_PARAM=MPL_UPPER)



CALL MPL_DOUBLESTACK%ALLOCATE(AUX,UBOUNDS_REAL,SIDE_PARAM=MPL_LOWER)

AUX=12.
AUX=AUX-0.5

WRITE(0,*) "AUX(2,3,4)",AUX(2,3,4)
WRITE(0,*) "SIZE(AUX)",SIZE(AUX)
WRITE(0,*) "SHAPE(AUX)",SHAPE(AUX)
WRITE(0,*) "KIND(AUX)",KIND(AUX)

CALL MPL_DOUBLESTACK%DEALLOCATE(AUX,SIDE_PARAM=MPL_LOWER)

END PROGRAM ESSAI_ALLOCATION_CHECKS_STACK_300
