PROGRAM ALLOC_ZERO_300

USE MPL_DOUBLESTACK_MOD, ONLY : MPL_DOUBLESTACK
USE EC_PARKIND, ONLY     : JPIM, JPIB, JPRM, JPRD
USE ISO_C_BINDING, ONLY : C_INT8_T

IMPLICIT NONE
INTEGER(KIND=C_INT8_T), PARAMETER :: MPL_LOWER=0
INTEGER(KIND=C_INT8_T), PARAMETER :: MPL_UPPER=1
REAL(KIND=JPRM), ALLOCATABLE, TARGET :: DOUBLE_STACK(:)

INTEGER*8 :: IL_MPL_DOUBLESTACK_SIZE
INTEGER*4 :: IL_BUF_SIZE(1)

REAL(KIND=JPRM), POINTER :: FOUBUF(:), FOUBUF_IN(:)

IL_MPL_DOUBLESTACK_SIZE=300*1024_8**2  ! 300 MBytes
IL_BUF_SIZE=0      ! essai allocation de taille nulle

CALL MPL_DOUBLESTACK%INIT(IL_MPL_DOUBLESTACK_SIZE)

!allocation de FOUBUF sur le bas de la pile
CALL MPL_DOUBLESTACK%ALLOCATE(FOUBUF,IL_BUF_SIZE,SIDE_PARAM=MPL_LOWER)

!allocation de FOUBUF_IN sur le haut de la pile
CALL MPL_DOUBLESTACK%ALLOCATE(FOUBUF_IN,IL_BUF_SIZE,SIDE_PARAM=MPL_UPPER)

if (.not. associated(foubuf_in)) write (0,*) "foubuf_in non associé"
if (.not. associated(foubuf)) write (0,*) "foubuf non associé"
CALL MPL_DOUBLESTACK%DEALLOCATE(FOUBUF)

CALL MPL_DOUBLESTACK%DEALLOCATE(FOUBUF_IN)

END PROGRAM ALLOC_ZERO_300
