PROGRAM ESSAI_STACK_300

USE MPL_DOUBLESTACK_MOD, ONLY : MPL_DOUBLESTACK
USE EC_PARKIND, ONLY     : JPIM, JPIB, JPRM, JPRD

IMPLICIT NONE

REAL(KIND=JPRM), ALLOCATABLE, TARGET :: DOUBLE_STACK(:)

INTEGER*8 :: IL_MPL_DOUBLESTACK_SIZE
INTEGER*4 :: IL_BUF_SIZE(1)

REAL(KIND=JPRM), POINTER :: FOUBUF(:), FOUBUF_IN(:)

IL_MPL_DOUBLESTACK_SIZE=300*1024_8**2  ! 300 MBytes
IL_BUF_SIZE=32*1024_8**2+1       ! un peu plus de 128 MBytes, en nombre d'éléments

CALL MPL_DOUBLESTACK%INIT(IL_MPL_DOUBLESTACK_SIZE)

!allocation de FOUBUF sur le bas de la pile
CALL MPL_DOUBLESTACK%ALLOCATE(FOUBUF,0,IL_BUF_SIZE)

!allocation de FOUBUF_IN sur le haut de la pile
CALL MPL_DOUBLESTACK%ALLOCATE(FOUBUF_IN,1,IL_BUF_SIZE)

FOUBUF=1.
FOUBUF_IN(:)=FOUBUF(:)+1.

WRITE(0,*) "FOUBUF_IN(2)",FOUBUF_IN(2)
WRITE(0,*) "SIZE(FOUBUF), SIZE(FOUBUF_IN)",SIZE(FOUBUF),SIZE(FOUBUF_IN)

CALL MPL_DOUBLESTACK%DEALLOCATE(FOUBUF,0)

CALL MPL_DOUBLESTACK%DEALLOCATE(FOUBUF_IN,1)

END PROGRAM ESSAI_STACK_300
